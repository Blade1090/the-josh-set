import fs from 'node:fs';

const BASE='https://dt.gameye.app/data/streaming/images/items/v1/';
const audit=JSON.parse(fs.readFileSync('audit-out/art-department-audit.json','utf8'));
const existing=fs.existsSync('cover-gameye-retail.js')?fs.readFileSync('cover-gameye-retail.js','utf8'):'';
let prior={};
const m=existing.match(/window\.SHELFCHECK_GAMEYE_RETAIL=(\{.*?\});\n/s);
if(m){try{prior=JSON.parse(m[1])}catch{}}

function isWebP(buf){return buf.length>=12&&buf.toString('ascii',0,4)==='RIFF'&&buf.toString('ascii',8,12)==='WEBP'}
async function verify(url){
  try{
    const r=await fetch(url,{headers:{'User-Agent':'ShelfCheck-ArtDepartment/1.2','Accept':'image/webp,image/*,*/*;q=0.8'}});
    if(!r.ok)return{ok:false,status:r.status};
    const b=Buffer.from(await r.arrayBuffer());
    const formatOk=isWebP(b),sizeOk=b.length>=45000;
    return{ok:formatOk&&sizeOk,status:r.status,bytes:b.length,formatOk,sizeOk,contentType:r.headers.get('content-type')||''};
  }catch(e){return{ok:false,status:0,error:String(e)}}
}

const targets=(audit.candidates||[]).filter(r=>r.autoCandidate&&r.gameye?.[0]?.image?.file);
const promoted={...prior},evidence=[];
let next=0;
const workers=Array.from({length:8},async()=>{
  while(true){
    const i=next++;if(i>=targets.length)return;
    const r=targets[i],g=r.gameye[0],url=BASE+g.image.file;
    const check=await verify(url);
    evidence.push({id:r.id,title:r.title,gameyeId:g.id,gameyeTitle:g.title,country:g.country_id,width:g.image.width,height:g.image.height,url,...check});
    if(check.ok)promoted[String(r.id)]=url;
    if((i+1)%25===0)console.log(`verified ${i+1}/${targets.length}`);
  }
});
await Promise.all(workers);

const ordered=Object.fromEntries(Object.entries(promoted).sort((a,b)=>Number(a[0])-Number(b[0])));
const meta={generatedAt:new Date().toISOString(),source:'GameEye art_front retail candidate pipeline',base:BASE,total:Object.keys(ordered).length,verifiedThisRun:evidence.filter(x=>x.ok).length,rejectedThisRun:evidence.filter(x=>!x.ok).length,minWidth:500,minHeight:700,minBytes:45000};
fs.writeFileSync('cover-gameye-retail.js',`// Generated by tools/promote-gameye-retail.mjs. Exact-title/curated-alias, portrait, quality-gated GameEye PS4 art_front only.\nwindow.SHELFCHECK_GAMEYE_RETAIL=${JSON.stringify(ordered)};\nwindow.SHELFCHECK_GAMEYE_RETAIL_META=${JSON.stringify(meta)};\n`);
fs.writeFileSync('audit-out/art-department-gameye-promotions.json',JSON.stringify({meta,evidence:evidence.sort((a,b)=>a.id-b.id)},null,2));
console.log(JSON.stringify(meta,null,2));
