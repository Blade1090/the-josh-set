// Build hltb-v105-research.js from audit-out/hltb-research-decisions.json + GameEye candidates.
//
// Usage: node tools/hltb-research-build.mjs [audit-out/hltb-runtime-qa.json] [audit-out/gameye-hltb-candidates.json]
//
// 1. Regenerates the ADD_GAMEYE decisions: an identity with no verified timing gets GameEye's
//    mirrored HLTB hours only when every exact normalized PS4 match that carries HLTB data agrees
//    (all main values within 10%); otherwise it is left for review. Manual decisions
//    (VERIFY_EXISTING / REJECT_LIKELY / WITHHOLD_LIKELY / CHANGE_*) are preserved untouched.
// 2. Writes the runtime layer. It keys rows by the exact HLTB map key hltbFor() resolves, never
//    alters a row that already carries verified timing (only VERIFY_EXISTING may upgrade q on a
//    LIKELY row), and fills times only where none exist.
import fs from 'node:fs';

const qaPath = process.argv[2] || 'audit-out/hltb-runtime-qa.pre-v105.json'; // audit WITHOUT this layer
const candPath = process.argv[3] || 'audit-out/gameye-hltb-candidates.json';
const decPath = 'audit-out/hltb-research-decisions.json';
const qa = JSON.parse(fs.readFileSync(qaPath, 'utf8'));
const rowsById = new Map(qa.rows.map((r) => [r.id, r]));
const cand = fs.existsSync(candPath) ? JSON.parse(fs.readFileSync(candPath, 'utf8')) : {};
const book = JSON.parse(fs.readFileSync(decPath, 'utf8'));
const manual = book.decisions.filter((d) => d.action !== 'ADD_GAMEYE' && d.action !== 'GAMEYE_REVIEW');
const manualIds = new Set(manual.map((d) => d.id));
const norm = (s) => String(s ?? '').normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[’'`]/g, '').replaceAll('&', ' and ').match(/[a-z0-9]+/g)?.join(' ') || '';

const adds = [], reviews = [];
for (const c of Object.values(cand)) {
  const r = rowsById.get(c.id);
  if (!r || manualIds.has(c.id) || r.class !== 'NO_VERIFIED_MATCH') continue;
  const timed = c.matches.filter((m) => [m.main, m.extras, m.completionist].some((v) => v != null));
  if (!timed.length) continue;
  const mains = timed.map((m) => m.main).filter((v) => v != null);
  const spread = mains.length ? (Math.max(...mains) - Math.min(...mains)) / Math.min(...mains) : 0;
  const sigs = new Map();
  for (const m of timed) { const k = JSON.stringify([m.main, m.extras, m.completionist]); sigs.set(k, (sigs.get(k) || 0) + 1); }
  const [best] = [...sigs.entries()].sort((a, b) => b[1] - a[1]);
  const [a, e, cpl] = JSON.parse(best[0]);
  const src = timed.find((m) => JSON.stringify([m.main, m.extras, m.completionist]) === best[0]);
  const entry = { id: c.id, title: c.title, matchedTitle: src.gameyeTitle, gameyeId: src.gameyeId, main: a, extras: e, completionist: cpl,
    evidence: `GameEye PS4 item ${src.gameyeId} ("${src.gameyeTitle}") exact normalized title/alias match; HLTB block main_story/main_sides/completionist (seconds -> hours); ${timed.length} PS4 record(s) with HLTB data${sigs.size > 1 ? `, ${sigs.size} distinct value sets, main spread ${(spread * 100).toFixed(1)}%` : ', all identical'}` };
  if (spread > 0.10) reviews.push({ ...entry, action: 'GAMEYE_REVIEW', evidence: entry.evidence + ' -- conflicting values, not applied' });
  else adds.push({ ...entry, action: 'ADD_GAMEYE' });
}
book.decisions = [...manual, ...adds, ...reviews];
fs.writeFileSync(decPath, JSON.stringify(book, null, 1));

// Runtime rows: [hltbKey, title, a, e, c, q, matchedTitle, source]
const layer = [];
for (const d of book.decisions) {
  const r = rowsById.get(d.id); if (!r) continue;
  const key = r.hltbKey || norm(r.title); // the exact key hltbFor() resolves (may be an alias key)
  if (d.action === 'VERIFY_EXISTING') layer.push([key, r.title, null, null, null, d.kind, null, 'curator review 2026-09-28']);
  else if (d.action === 'REJECT_LIKELY') layer.push([key, r.title, null, null, null, 'REJECTED_MAPPING', d.matchedTitle, d.evidence]);
  else if (d.action === 'WITHHOLD_LIKELY') layer.push([key, r.title, null, null, null, 'HLTB_NO_VERIFIED_MATCH', d.matchedTitle, d.evidence]);
  else if (d.action === 'ADD_GAMEYE') layer.push([norm(r.title), r.title, d.main, d.extras, d.completionist, 'GAMEYE_HLTB', d.matchedTitle, `GAMEYE:${d.gameyeId}`]);
}
const js = `// ShelfCheck v1.05 HLTB research layer. Generated by tools/hltb-research-build.mjs from
// audit-out/hltb-research-decisions.json -- edit the decisions, not this file.
// GAMEYE_HLTB rows are HowLongToBeat hours mirrored by GameEye for an exact PS4 title match.
// Rows never overwrite verified timing: they fill empty records, upgrade reviewed LIKELY rows,
// or remove a mapping a curator rejected.
(()=>{const rows=${JSON.stringify(layer)};const VERIFIED=new Set(['AUTO_OK','WEB_OK','MANUAL_OK','INHERITED_OK','GAMEYE_HLTB']);const timed=d=>d&&[d.a,d.e,d.c].some(v=>v!=null);let tries=0,t=setInterval(()=>{if(typeof HLTB==='undefined'||typeof norm!=='function'||!hltbReady){if(++tries>200)clearInterval(t);return}clearInterval(t);let n=0;for(const [k,title,a,e,c,q,m,src] of rows){const old=HLTB.get(k);if(timed(old)&&VERIFIED.has(old.q))continue;if(q==='MANUAL_OK'||q==='INHERITED_OK'){if(timed(old)){HLTB.set(k,{...old,q,src});n++}continue}if(q==='REJECTED_MAPPING'||q==='HLTB_NO_VERIFIED_MATCH'){HLTB.set(k,{t:title,q,rejected:m,note:src});n++;continue}if(timed(old))continue;const d={...(old||{}),t:title,m,q,src};if(a!=null)d.a=a;if(e!=null)d.e=e;if(c!=null)d.c=c;HLTB.set(k,d);n++}console.info('ShelfCheck HLTB v1.05 research layer applied:',n,'records');},50)})();
`;
fs.writeFileSync('hltb-v105-research.js', js);
console.log(JSON.stringify({ manual: manual.length, addGameye: adds.length, gameyeReview: reviews.length, layerRows: layer.length }, null, 2));
